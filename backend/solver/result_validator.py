# 6. P1 AND P2
# ================================================================

def validate_p1_p2(
    timetable,
    solver
):
    """
    Validate the requirement:

        P1 and P2 must not be empty.

    This is checked for every batch and every day.
    """

    days = timetable.num_days

    errors = []

    for b in range(
        len(timetable.batches)
    ):

        for d in range(days):

            for p in (0, 1):

                occupied = is_period_occupied(
                    timetable,
                    solver,
                    b,
                    d,
                    p
                )

                if not occupied:

                    errors.append(
                        ValidationError(
                            "p1_p2_empty",
                            "P1/P2 cannot be empty.",
                            {
                                "batch":
                                    get_batch_name(
                                        timetable,
                                        b
                                    ),
                                "day":
                                    get_day_name(
                                        timetable,
                                        d
                                    ),
                                "period":
                                    p + 1
                            }
                        )
                    )

    return errors


# ================================================================
# 7. NAAN MUDALVAN CONTINUITY
# ================================================================

def validate_naan_mudalvan(
    timetable,
    solver
):
    """
    Verify that Naan Mudalvan periods form exactly one
    continuous block.
    """

    required = get_naan_periods(
        timetable
    )

    if required <= 0:
        return []

    days = timetable.num_days
    periods = timetable.num_periods

    errors = []

    for b in range(
        len(timetable.batches)
    ):

        scheduled = []

        for d in range(days):

            for p in range(periods):

                if solver.Value(
                    timetable.naan_mudalvan[
                        b, d, p
                    ]
                ):

                    scheduled.append(
                        (
                            d,
                            p
                        )
                    )

        if len(scheduled) != required:

            errors.append(
                ValidationError(
                    "naan_mudalvan_count",
                    "Naan Mudalvan does not have "
                    "the required number of periods.",
                    {
                        "batch":
                            get_batch_name(
                                timetable,
                                b
                            ),
                        "required":
                            required,
                        "actual":
                            len(scheduled)
                    }
                )
            )

            continue

        # --------------------------------------------------------
        # Must all be on the same day.
        # --------------------------------------------------------

        used_days = {
            d
            for d, p in scheduled
        }

        if len(used_days) != 1:

            errors.append(
                ValidationError(
                    "naan_mudalvan_day",
                    "Naan Mudalvan is split across "
                    "multiple days.",
                    {
                        "batch":
                            get_batch_name(
                                timetable,
                                b
                            ),
                        "days":
                            list(used_days)
                    }
                )
            )

            continue

        # --------------------------------------------------------
        # Periods must be consecutive.
        # --------------------------------------------------------

        periods_used = sorted(
            p
            for d, p in scheduled
        )

        for i in range(
            1,
            len(periods_used)
        ):

            if (
                periods_used[i]
                !=
                periods_used[i - 1] + 1
            ):

                errors.append(
                    ValidationError(
                        "naan_mudalvan_continuity",
                        "Naan Mudalvan periods "
                        "are not continuous.",
                        {
                            "batch":
                                get_batch_name(
                                    timetable,
                                    b
                                ),
                            "periods":
                                [
                                    p + 1
                                    for p
                                    in periods_used
                                ]
                        }
                    )
                )

                break

    return errors


