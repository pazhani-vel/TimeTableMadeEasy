# 5. SPECIAL CLASSES
# ================================================================

def validate_special_classes(
    timetable,
    solver
):
    """
    Validate Audit and IOC.

    Both must only occur in P7/P8.
    """

    days = timetable.num_days
    periods = timetable.num_periods

    errors = []

    allowed = {
        6,
        7
    }

    for b in range(
        len(timetable.batches)
    ):

        for d in range(days):

            for p in range(periods):

                audit = solver.Value(
                    timetable.audit[
                        b, d, p
                    ]
                )

                ioc = solver.Value(
                    timetable.ioc[
                        b, d, p
                    ]
                )

                if audit and p not in allowed:

                    errors.append(
                        ValidationError(
                            "audit_period",
                            "Audit is scheduled "
                            "outside P7/P8.",
                            {
                                "batch":
                                    get_batch_name(
                                        timetable,
                                        b
                                    ),
                                "day":
                                    get_day_name(
                                        timetable,
                                        d
                                    ),
                                "period":
                                    p + 1
                            }
                        )
                    )

                if ioc and p not in allowed:

                    errors.append(
                        ValidationError(
                            "ioc_period",
                            "IOC is scheduled "
                            "outside P7/P8.",
                            {
                                "batch":
                                    get_batch_name(
                                        timetable,
                                        b
                                    ),
                                "day":
                                    get_day_name(
                                        timetable,
                                        d
                                    ),
                                "period":
                                    p + 1
                            }
                        )
                    )

                # ------------------------------------------------
                # Audit + IOC + Naan Mudalvan cannot occur
                # simultaneously.
                # ------------------------------------------------

                naan = solver.Value(
                    timetable.naan_mudalvan[
                        b, d, p
                    ]
                )

                if (
                    audit
                    +
                    ioc
                    +
                    naan
                    > 1
                ):

                    errors.append(
                        ValidationError(
                            "special_class_conflict",
                            "Multiple special activities "
                            "are scheduled at the same time.",
                            {
                                "batch":
                                    get_batch_name(
                                        timetable,
                                        b
                                    ),
                                "day":
                                    get_day_name(
                                        timetable,
                                        d
                                    ),
                                "period":
                                    p + 1
                            }
                        )
                    )

    return errors


