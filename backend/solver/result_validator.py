# SOFT: PREFERRED DAYS
# ================================================================

def validate_preferred_days(
    timetable,
    solver
):
    """
    Preferred-day violations are warnings, not errors.
    """

    subjects = timetable.subjects
    batches = timetable.batches

    days = timetable.num_days
    periods = timetable.num_periods

    theory_y = timetable.theory_y
    lab_y = timetable.lab_y

    warnings = []

    day_index = {
        normalize_day(day): i
        for i, day
        in enumerate(timetable.days)
    }

    for s, subject in enumerate(subjects):

        preferred = get_preferred_days(
            subject,
            day_index
        )

        if not preferred:
            continue

        for b in range(len(batches)):

            for d in range(days):

                used = False

                for p in range(periods):

                    if (
                        solver.Value(
                            theory_y[
                                s, b, d, p
                            ]
                        )
                        or
                        solver.Value(
                            lab_y[
                                s, b, d, p
                            ]
                        )
                    ):

                        used = True
                        break

                if used and d not in preferred:

                    warnings.append(
                        ValidationError(
                            "preferred_day",
                            "Subject is scheduled "
                            "on a non-preferred day.",
                            {
                                "subject":
                                    get_subject_name(
                                        timetable,
                                        s
                                    ),
                                "batch":
                                    get_batch_name(
                                        timetable,
                                        b
                                    ),
                                "day":
                                    get_day_name(
                                        timetable,
                                        d
                                    )
                            }
                        )
                    )

    return warnings


# ================================================================
# SOFT: GAPS
# ================================================================

def validate_gaps(
    timetable,
    solver
):
    """
    Find internal gaps in a batch's day.

    These are warnings because gaps are soft constraints.
    """

    days = timetable.num_days
    periods = timetable.num_periods

    warnings = []

    for b in range(
        len(timetable.batches)
    ):

        for d in range(days):

            occupied = [
                is_period_occupied(
                    timetable,
                    solver,
                    b,
                    d,
                    p
                )
                for p in range(periods)
            ]

            occupied_positions = [
                i
                for i, value
                in enumerate(occupied)
                if value
            ]

            if not occupied_positions:
                continue

            first = min(
                occupied_positions
            )

            last = max(
                occupied_positions
            )

            for p in range(
                first + 1,
                last
            ):

                if not occupied[p]:

                    warnings.append(
                        ValidationError(
                            "internal_gap",
                            "Batch has an internal "
                            "free-period gap.",
                            {
                                "batch":
                                    get_batch_name(
                                        timetable,
                                        b
                                    ),
                                "day":
                                    get_day_name(
                                        timetable,
                                        d
                                    ),
                                "period":
                                    p + 1
                            }
                        )
                    )

    return warnings


