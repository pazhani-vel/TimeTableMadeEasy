# 2. FACULTY CONFLICTS
# ================================================================

def validate_faculty_conflicts(
    timetable,
    solver
):
    """
    A faculty member cannot teach two classes at the same time.
    """

    subjects = timetable.subjects
    batches = timetable.batches

    days = timetable.num_days
    periods = timetable.num_periods

    theory_y = timetable.theory_y
    lab_y = timetable.lab_y

    errors = []

    faculty_schedule = defaultdict(list)

    for s, subject in enumerate(subjects):

        faculty = get_subject_faculty(
            subject
        )

        if faculty is None:
            continue

        for b in range(len(batches)):

            for d in range(days):

                for p in range(periods):

                    theory = solver.Value(
                        theory_y[
                            s, b, d, p
                        ]
                    )

                    lab = solver.Value(
                        lab_y[
                            s, b, d, p
                        ]
                    )

                    if theory or lab:

                        faculty_schedule[
                            (
                                str(faculty),
                                d,
                                p
                            )
                        ].append(
                            (
                                s,
                                b
                            )
                        )

    for key, classes in faculty_schedule.items():

        if len(classes) > 1:

            faculty, d, p = key

            errors.append(
                ValidationError(
                    "faculty_conflict",
                    "A faculty member is assigned "
                    "to multiple classes at the same time.",
                    {
                        "faculty": faculty,
                        "day": get_day_name(
                            timetable,
                            d
                        ),
                        "period": p + 1,
                        "classes": [
                            {
                                "subject":
                                    get_subject_name(
                                        timetable,
                                        s
                                    ),
                                "batch":
                                    get_batch_name(
                                        timetable,
                                        b
                                    )
                            }
                            for s, b in classes
                        ]
                    }
                )
            )

    return errors


# ================================================================
# 3. SUBJECT PERIOD COUNT
# ================================================================

def validate_subject_periods(
    timetable,
    solver
):
    """
    Verify that every subject receives the required number
    of periods.

    Only checks batches that the subject is assigned to
    (via batch_id). Non-target batches are skipped.
    """

    subjects = timetable.subjects
    batches = timetable.batches

    days = timetable.num_days
    periods = timetable.num_periods

    theory_y = timetable.theory_y
    lab_y = timetable.lab_y

    errors = []

    for s, subject in enumerate(subjects):

        required = get_required_periods(
            subject
        )

        if required <= 0:
            continue

        # Determine target batches
        subject_batch_id = (
            subject.get("batch_id")
            if isinstance(subject, dict)
            else None
        )

        target_batches = []
        for b in range(len(batches)):
            if subject_batch_id is not None:
                batch_id = (
                    batches[b].get("id")
                    if isinstance(batches[b], dict)
                    else batches[b]
                )
                if str(batch_id) != str(subject_batch_id):
                    continue
            target_batches.append(b)

        for b in target_batches:

            actual = 0

            for d in range(days):

                for p in range(periods):

                    actual += solver.Value(
                        theory_y[
                            s, b, d, p
                        ]
                    )

                    actual += solver.Value(
                        lab_y[
                            s, b, d, p
                        ]
                    )

            if actual != required:

                errors.append(
                    ValidationError(
                        "subject_period_count",
                        "Subject does not have "
                        "the required number of periods.",
                        {
                            "subject":
                                get_subject_name(
                                    timetable,
                                    s
                                ),
                            "batch":
                                get_batch_name(
                                    timetable,
                                    b
                                ),
                            "required":
                                required,
                            "actual":
                                actual
                        }
                    )
                )

    return errors


# ================================================================
# 4. LAB RESOURCE VALIDATION
# ================================================================

def validate_lab_resources(
    timetable,
    solver
):
    """
    Verify that a physical laboratory is not used by
    multiple batches at the same time.
    """

    if not hasattr(
        timetable,
        "lab_assignment"
    ):
        return []

    labs = timetable.labs

    days = timetable.num_days
    periods = timetable.num_periods

    errors = []

    for l in range(len(labs)):

        for d in range(days):

            for p in range(periods):

                usage = []

                for key, variable in (
                    timetable.lab_assignment.items()
                ):

                    s, b, kd, kp, kl = key

                    if kl != l:
                        continue

                    # A two-period lab occupies both periods.
                    if kd == d and (
                        kp == p
                        or kp + 1 == p
                    ):

                        if solver.Value(
                            variable
                        ):
                            usage.append(
                                (
                                    s,
                                    b,
                                    kp
                                )
                            )

                if len(usage) > 1:

                    errors.append(
                        ValidationError(
                            "lab_conflict",
                            "A physical laboratory is "
                            "assigned to multiple batches "
                            "at the same time.",
                            {
                                "lab":
                                    get_lab_name(
                                        timetable,
                                        l
                                    ),
                                "day":
                                    get_day_name(
                                        timetable,
                                        d
                                    ),
                                "period":
                                    p + 1,
                                "usage":
                                    usage
                            }
                        )
                    )

    return errors


