# SOFT: SUBJECT DISTRIBUTION
# ================================================================

def validate_distribution(
    timetable,
    solver
):
    """
    Find subjects split into multiple blocks on the same day.

    Example:

        DBMS DBMS FREE DBMS

    This creates a warning.
    """

    subjects = timetable.subjects
    batches = timetable.batches

    days = timetable.num_days
    periods = timetable.num_periods

    theory_y = timetable.theory_y
    lab_y = timetable.lab_y

    warnings = []

    for s in range(len(subjects)):

        for b in range(len(batches)):

            for d in range(days):

                blocks = 0
                previous = False

                for p in range(periods):

                    current = (
                        solver.Value(
                            theory_y[
                                s, b, d, p
                            ]
                        )
                        or
                        solver.Value(
                            lab_y[
                                s, b, d, p
                            ]
                        )
                    )

                    if current and not previous:

                        blocks += 1

                    previous = current

                if blocks > 1:

                    warnings.append(
                        ValidationError(
                            "subject_distribution",
                            "Subject is split into "
                            "multiple blocks on the same day.",
                            {
                                "subject":
                                    get_subject_name(
                                        timetable,
                                        s
                                    ),
                                "batch":
                                    get_batch_name(
                                        timetable,
                                        b
                                    ),
                                "day":
                                    get_day_name(
                                        timetable,
                                        d
                                    ),
                                "blocks":
                                    blocks
                            }
                        )
                    )

    return warnings


# ================================================================
# OCCUPANCY
# ================================================================

def is_period_occupied(
    timetable,
    solver,
    batch,
    day,
    period
):
    """
    Return True if the batch has any class in the period.
    """

    for s in range(
        len(timetable.subjects)
    ):

        if solver.Value(
            timetable.theory_y[
                s, batch, day, period
            ]
        ):
            return True

        if solver.Value(
            timetable.lab_y[
                s, batch, day, period
            ]
        ):
            return True

    if solver.Value(
        timetable.naan_mudalvan[
            batch, day, period
        ]
    ):
        return True

    if solver.Value(
        timetable.audit[
            batch, day, period
        ]
    ):
        return True

    if solver.Value(
        timetable.ioc[
            batch, day, period
        ]
    ):
        return True

    return False


