# HELPERS
# ================================================================

def get_required_periods(subject):

    if not isinstance(subject, dict):
        return 0

    theory = subject.get(
        "theory_hours",
        subject.get(
            "theory_periods",
            0
        )
    )

    lab = subject.get(
        "lab_hours",
        subject.get(
            "lab_periods",
            subject.get(
                "lab",
                0
            )
        )
    )

    try:
        theory = int(theory)
    except (
        TypeError,
        ValueError
    ):
        theory = 0

    try:
        lab = int(lab)
    except (
        TypeError,
        ValueError
    ):
        lab = 0

    return theory + lab


def get_naan_periods(timetable):

    value = timetable.data.get(
        "naan_mudalvan_periods",
        timetable.data.get(
            "naan_mudalvan_hours",
            0
        )
    )

    try:
        return int(value)
    except (
        TypeError,
        ValueError
    ):
        return 0


def get_subject_faculty(subject):

    if not isinstance(subject, dict):
        return None

    return (
        subject.get("faculty")
        or subject.get("faculty_id")
        or subject.get("facultyId")
        or subject.get("teacher")
    )


def get_preferred_days(
    subject,
    day_index
):

    if not isinstance(subject, dict):
        return set()

    value = subject.get(
        "preferred_days"
    )

    if value is None:
        value = subject.get(
            "preferred_day"
        )

    if value is None:
        return set()

    if not isinstance(value, list):
        value = [value]

    result = set()

    for day in value:

        if isinstance(day, int):

            if (
                0 <= day
                <
                len(day_index)
            ):
                result.add(day)

        else:

            index = day_index.get(
                normalize_day(day)
            )

            if index is not None:
                result.add(index)

    return result


def normalize_day(day):
    return str(
        day
    ).strip().lower()


def get_subject_name(
    timetable,
    index
):

    subject = timetable.subjects[index]

    if isinstance(subject, dict):

        return (
            subject.get("name")
            or subject.get("subject_name")
            or subject.get("code")
            or f"subject_{index}"
        )

    return str(subject)


def get_batch_name(
    timetable,
    index
):

    batch = timetable.batches[index]

    if isinstance(batch, dict):

        return (
            batch.get("name")
            or batch.get("batch_name")
            or batch.get("code")
            or f"batch_{index}"
        )

    return str(batch)


def get_lab_name(
    timetable,
    index
):

    lab = timetable.labs[index]

    if isinstance(lab, dict):

        return (
            lab.get("name")
            or lab.get("lab_name")
            or lab.get("code")
            or f"lab_{index}"
        )

    return str(lab)


def get_day_name(
    timetable,
    index
):

    if hasattr(
        timetable,
        "days"
    ):

        if (
            0 <= index
            <
            len(timetable.days)
        ):
            return timetable.days[index]

    return f"Day {index + 1}"


