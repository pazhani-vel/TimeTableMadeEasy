from collections import defaultdict
from ortools.sat.python import cp_model


class ValidationError:
    def __init__(
        self,
        constraint,
        message,
        details=None
    ):
        self.constraint = constraint
        self.message = message
        self.details = details or {}

    def to_dict(self):
        return {
            "constraint": self.constraint,
            "message": self.message,
            "details": self.details
        }


def validate_result(timetable, solver):
    """
    Validate the timetable generated by OR-Tools.

    This validator checks the FINAL solver output.

    Returns:

        {
            "valid": True/False,
            "errors": [...],
            "warnings": [...]
        }

    Hard-constraint violations are returned as errors.

    Soft-constraint violations are returned as warnings.
    """

    errors = []
    warnings = []

    # ============================================================
    # CHECK SOLVER STATUS
    # ============================================================

    status_value = solver.ResponseProto().status

    if status_value == cp_model.OPTIMAL:
        status = "OPTIMAL"
    elif status_value == cp_model.FEASIBLE:
        status = "FEASIBLE"
    elif status_value == cp_model.INFEASIBLE:
        status = "INFEASIBLE"
    elif status_value == cp_model.MODEL_INVALID:
        status = "MODEL_INVALID"
    elif status_value == cp_model.UNKNOWN:
        status = "UNKNOWN"
    else:
        status = str(status_value)

    if status not in (
        "OPTIMAL",
        "FEASIBLE"
    ):
        errors.append(
            ValidationError(
                "solver_status",
                f"Solver did not produce a valid timetable. "
                f"Status: {status}"
            )
        )

        return build_result(
            errors,
            warnings
        )

    # ============================================================
    # HARD CONSTRAINT VALIDATION
    # ============================================================

    errors.extend(
        validate_batch_conflicts(
            timetable,
            solver
        )
    )

    errors.extend(
        validate_faculty_conflicts(
            timetable,
            solver
        )
    )

    errors.extend(
        validate_subject_periods(
            timetable,
            solver
        )
    )

    errors.extend(
        validate_lab_resources(
            timetable,
            solver
        )
    )

    errors.extend(
        validate_special_classes(
            timetable,
            solver
        )
    )

    errors.extend(
        validate_p1_p2(
            timetable,
            solver
        )
    )

    errors.extend(
        validate_naan_mudalvan(
            timetable,
            solver
        )
    )

    # ============================================================
    # SOFT CONSTRAINT VALIDATION
    # ============================================================

    warnings.extend(
        validate_preferred_days(
            timetable,
            solver
        )
    )

    warnings.extend(
        validate_gaps(
            timetable,
            solver
        )
    )

    warnings.extend(
        validate_distribution(
            timetable,
            solver
        )
    )

    return build_result(
        errors,
        warnings
    )


# ================================================================
# 1. BATCH CONFLICTS
# ================================================================

def validate_batch_conflicts(
    timetable,
    solver
):
    """
    A batch cannot have two classes in the same period.
    """

    model = timetable.model

    subjects = timetable.subjects
    batches = timetable.batches

    days = timetable.num_days
    periods = timetable.num_periods

    theory_y = timetable.theory_y
    lab_y = timetable.lab_y

    errors = []

    for b in range(len(batches)):

        for d in range(days):

            for p in range(periods):

                count = 0

                for s in range(len(subjects)):

                    count += solver.Value(
                        theory_y[
                            s, b, d, p
                        ]
                    )

                    count += solver.Value(
                        lab_y[
                            s, b, d, p
                        ]
                    )

                # Special activities
                count += solver.Value(
                    timetable.naan_mudalvan[
                        b, d, p
                    ]
                )

                count += solver.Value(
                    timetable.audit[
                        b, d, p
                    ]
                )

                count += solver.Value(
                    timetable.ioc[
                        b, d, p
                    ]
                )

                if count > 1:

                    errors.append(
                        ValidationError(
                            "batch_conflict",
                            "A batch has multiple "
                            "classes in the same period.",
                            {
                                "batch": get_batch_name(
                                    timetable,
                                    b
                                ),
                                "day": get_day_name(
                                    timetable,
                                    d
                                ),
                                "period": p + 1,
                                "count": count
                            }
                        )
                    )

    return errors


