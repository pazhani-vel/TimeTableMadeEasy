# ================================================================

def build_result(
    errors,
    warnings
):

    return {
        "valid": len(errors) == 0,
        "errors": [
            error.to_dict()
            for error in errors
        ],
        "warnings": [
            warning.to_dict()
            for warning in warnings
        ],
        "error_count": len(errors),
        "warning_count": len(warnings)
    }